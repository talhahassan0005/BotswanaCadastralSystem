/* Generate apps/web/lib/refMarksData.ts from the client's official national
 * reference-mark PDF export (client req 2026-10-22, "ye lo jo refrencemark
 * mange thay" — "here's the reference marks you asked for", replacing the
 * earlier CONTROL POINTS-folder-derived seed, which the client had flagged
 * as dummy/incomplete data on the Locator Map).
 *
 * Source: public/refrence-marks.pdf (55 pages, "Botswana Reference Marks",
 * columns Area/Type/OldId/X_LO/Y_LO/OrthoH/Village) — extracted with
 * pdfplumber (table-grid-aware, far more reliable on this file than a plain
 * text dump) into CONTROL POINTS/NATIONAL/national_reference_marks.csv
 * (columns: area,oldid,east,north,ortho,village — east/north already
 * swapped from the PDF's X_LO/Y_LO, which use Botswana's Lo convention of
 * X=northing/Y=easting, matching genRefMarks.ts's own convention).
 *
 * The PDF has NO explicit Lo-belt label per row — only an "Area" degree-
 * square code (e.g. "2227" = 22°S/27°E square, confirmed against several
 * known towns: 2425=Gaborone, 2127=Francistown, 2622=Tsabong, ...). Botswana's
 * Lo belts are 2° wide, centred on odd meridians (21/23/25/27/29), so the
 * nearest belt to a given longitude square is `2*floor(lonSquare/2)+1`.
 * Rather than trust that guess blindly, each row tries that belt AND its two
 * neighbours (±2) through the same transformPoint() the rest of the app
 * uses, and keeps whichever result's own lat/lon actually falls back inside
 * the Area code's own 1°×1° square — the same kind of round-trip sanity
 * check genRefMarks.ts already does for the whole country, just precise to
 * the row's own square instead of the whole country's bounding box. This is
 * what caught the exact Francistown-area quirk genRefMarks.ts had to special
 * -case by hand (several "2027"/"2127" Tati-area villages are really on the
 * Lo25 origin, not Lo27) — here it falls out of the validation automatically.
 *
 * Run: npx tsx scripts/genRefMarksFromPdf.ts
 */
import * as fs from "fs";
import * as path from "path";
import { transformPoint } from "../apps/web/lib/server/crs";

const SRC = path.join(__dirname, "..", "CONTROL POINTS", "NATIONAL", "national_reference_marks.csv");
const OUT = path.join(__dirname, "..", "apps", "web", "lib", "refMarksData.ts");

interface RefMark {
  id: string; number: string; name: string; type: string;
  lat: number; lon: number; description: string; status: string; region: string;
}

function parseCsvLine(line: string): string[] {
  // Simple CSV split — this file has no embedded commas/quotes (generated by
  // the Python cleanup script, not hand-edited), so a plain split is safe.
  return line.split(",");
}

const lines = fs.readFileSync(SRC, "utf8").split(/\r?\n/).filter(Boolean);
const [, ...dataLines] = lines; // drop header

const marks: RefMark[] = [];
const seen = new Set<string>();
let unverified = 0, converted = 0, duplicates = 0;
const perLocality: Record<string, { n: number; latSum: number; lonSum: number }> = {};

for (const line of dataLines) {
  const [areaS, oldid, eastS, northS, , village] = parseCsvLine(line);
  const area = areaS.trim();
  const east = Number(eastS);
  const north = Number(northS);
  if (!area || area.length !== 4 || !/^\d{4}$/.test(area) || !Number.isFinite(east) || !Number.isFinite(north)) continue;
  const latSquare = Number(area.slice(0, 2)); // degrees SOUTH
  const lonSquare = Number(area.slice(2, 4)); // degrees EAST
  const primaryBelt = 2 * Math.floor(lonSquare / 2) + 1;
  const candidates = [primaryBelt, primaryBelt - 2, primaryBelt + 2].filter((b) => b >= 13 && b <= 29);

  let best: { lat: number; lon: number; belt: number } | null = null;
  for (const belt of candidates) {
    let lat: number, lon: number;
    try {
      [lat, lon] = transformPoint(east, north, `Lo${belt}`, "WGS84");
    } catch {
      continue;
    }
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
    const inSquare = lat <= -latSquare && lat > -(latSquare + 1) && lon >= lonSquare && lon < lonSquare + 1;
    if (inSquare) { best = { lat, lon, belt }; break; } // first (= primary-first) match wins
    if (!best) best = { lat, lon, belt }; // keep the primary guess as fallback even if unverified
  }
  if (!best) continue;
  if (!(best.lat <= -latSquare && best.lat > -(latSquare + 1) && best.lon >= lonSquare && best.lon < lonSquare + 1)) {
    unverified++;
  }

  const name = (village || "").trim() || "UNKNOWN";
  const key = `${name}|${oldid.trim()}`;
  if (seen.has(key)) { duplicates++; continue; }
  seen.add(key);
  converted++;
  marks.push({
    id: key.replace(/[^A-Za-z0-9]/g, "_"),
    number: oldid.trim() || `(${area})`,
    name,
    type: "Reference mark",
    lat: Math.round(best.lat * 1e6) / 1e6,
    lon: Math.round(best.lon * 1e6) / 1e6,
    description: `Lo${best.belt}`,
    status: "In good order",
    region: name,
  });
  const pl = (perLocality[name] ??= { n: 0, latSum: 0, lonSum: 0 });
  pl.n++; pl.latSum += best.lat; pl.lonSum += best.lon;
}

const header = `// AUTO-GENERATED from the client's national reference-mark PDF export\n` +
  `// (public/refrence-marks.pdf) by scripts/genRefMarksFromPdf.ts — do not edit by hand.\n` +
  `// ${marks.length} reference marks across ${new Set(marks.map((m) => m.name)).size} localities (converted to WGS84).\n` +
  `import type { RefMark } from "./refmarks";\n\n` +
  `export const REF_MARKS_DATA: RefMark[] = `;
fs.writeFileSync(OUT, header + JSON.stringify(marks, null, 0) + ";\n", "utf8");

console.log(`converted=${converted} duplicates_skipped=${duplicates} unverified_square=${unverified}`);
console.log(`MARKS=${marks.length} localities=${new Set(marks.map((m) => m.name)).size}`);
console.log("per-locality centroid (spot-check a few against known towns):");
for (const [v, p] of Object.entries(perLocality).sort((a, b) => b[1].n - a[1].n).slice(0, 15)) {
  console.log(`  ${v.padEnd(20)} n=${String(p.n).padStart(4)}  lat=${(p.latSum / p.n).toFixed(3)} lon=${(p.lonSum / p.n).toFixed(3)}`);
}
